export type TranslationKey = keyof typeof zh
type TranslationParams = Record<string, string | number>

export const resolveInitialLanguage = (
  storedLanguage?: string | null,
  browserLanguage?: string,
): Language => {
  if (storedLanguage === 'zh-CN' || storedLanguage === 'en-US') {
    return storedLanguage
  }
  return browserLanguage?.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en-US'
}

const translate = (
  language: Language,
  key: TranslationKey,
  params?: TranslationParams,
): string => {
  const template = (language === 'zh-CN' ? zh : en)[key]
  if (!params) return template
  return Object.entries(params).reduce(
    (result, [name, value]) => result.split(`{${name}}`).join(String(value)),
    template,
  )
}

interface I18nContextValue {
  language: Language
  locale: Language
  setLanguage: (language: Language) => void
  toggleLanguage: () => void
  t: (key: TranslationKey, params?: TranslationParams) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => resolveInitialLanguage(
    typeof window === 'undefined' ? null : window.localStorage.getItem(LANGUAGE_STORAGE_KEY),
    typeof navigator === 'undefined' ? undefined : navigator.language,
  ))

  useEffect(() => {
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language)
    document.documentElement.lang = language
  }, [language])

  const value = useMemo<I18nContextValue>(() => ({
    language,
    locale: language,
    setLanguage,
    toggleLanguage: () => setLanguage((current) => (
      current === 'zh-CN' ? 'en-US' : 'zh-CN'
    )),
    t: (key, params) => translate(language, key, params),
  }), [language])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext)
  if (!context) throw new Error('useI18n must be used within I18nProvider')
  return context
}
