const getErrorMessage = (error: unknown) => {
  const apiError = error as {
    response?: { data?: { error?: string; message?: string } }
    message?: string
  }

  return apiError.response?.data?.error ?? apiError.response?.data?.message ?? apiError.message ?? 'Agent request failed'
}

const isAbortError = (error: unknown): boolean =>
  error instanceof Error && error.name === 'AbortError'

const createDemoProject = async (prompt: string) => {
  if (!localStorage.getItem('token')) {
    const unique = `${Date.now()}-${Math.random().toString(16).slice(2)}`
    const authResponse = await authApi.register(
      `phase5-${unique}@v0.local`,
      'password123',
      'Phase Five Demo',
    )
    localStorage.setItem('token', authResponse.data.token)
  }

  const projectResponse = await projectApi.create({
    name: `v0 Snapshot ${new Date().toLocaleTimeString()}`,
    description: prompt,
    settings: {
      framework: 'react',
      styling: 'tailwind',
      uiLibrary: 'shadcn',
    },
  })

  return projectResponse.data.project._id as string
}

export function V0Clone() {
  const navigate = useNavigate()
  const { chatId } = useParams<{ chatId: string }>()
  const [workspace, setWorkspace] = useState(createInitialWorkspaceState)
  const [draftPrompt, setDraftPrompt] = useState('')
  const [editDraft, setEditDraft] = useState('')
  const [submissionPending, setSubmissionPending] = useState(false)
  const [routeError, setRouteError] = useState<string>()
  const [modelOpen, setModelOpen] = useState(false)
  const [model, setModel] = useState('Mock provider')
  const [category, setCategory] = useState<'all' | Template['category']>('all')
  const [designMode, setDesignMode] = useState(true)
  const [deployOpen, setDeployOpen] = useState(false)
  const [copied, setCopied] = useState(false)
  const [workspaceSidebarCollapsed, setWorkspaceSidebarCollapsed] = useState(false)
  const [projectId, setProjectId] = useState('')
  const refreshRequestRef = useRef(0)
  const routeRequestRef = useRef(0)
  const pendingNavigationChatRef = useRef<string | null>(null)
  const rollbackInFlightRef = useRef(false)
  const monitorControllerRef = useRef<AbortController | null>(null)
  const submissionInFlightRef = useRef(false)
  const submissionIdRef = useRef(0)

  const visibleTemplates = useMemo(
    () => templates.filter((template) => category === 'all' || template.category === category),
    [category],
  )

  const selectedTemplate = useMemo(
    () => templates.find((template) => template.id === workspace.selectedTemplateId) ?? templates[0],
    [workspace.selectedTemplateId],
  )

  const currentPrompt = workspace.prompt || draftPrompt || selectedTemplate.prompt
  const selectedSnapshotFile = workspace.snapshot?.files.find(
    (file) => file.path === workspace.snapshot?.selectedFilePath,
  ) ?? workspace.snapshot?.files[0]
  const currentCode = selectedSnapshotFile?.content ?? sampleCode
  const currentFileName = selectedSnapshotFile?.path ?? 'generated-app.tsx'

  const refreshProjectData = async (id: string) => {
    const requestId = ++refreshRequestRef.current
    const [runsResponse, snapshotsResponse] = await Promise.all([
      agentApi.getRuns(id),
      projectApi.getSnapshots(id),
    ])
    if (requestId !== refreshRequestRef.current) {
      return null
    }
    setWorkspace((state) =>
      applySnapshotList(
        applyRunHistory(state, runsResponse.data.runs),
        snapshotsResponse.data.snapshots,
      ),
    )
    return snapshotsResponse.data.snapshots
  }

  useEffect(() => {
    const requestId = ++routeRequestRef.current
    setRouteError(undefined)
    setEditDraft('')

    if (!chatId) {
      monitorControllerRef.current?.abort()
      monitorControllerRef.current = null
      setProjectId('')
      setWorkspace(createInitialWorkspaceState())
      return
    }

    if (pendingNavigationChatRef.current === chatId) {
      pendingNavigationChatRef.current = null
      return
    }

    monitorControllerRef.current?.abort()
    monitorControllerRef.current = null
    setProjectId('')
    setWorkspace((state) => resetWorkspaceForChat(state))

    void (async () => {
      try {
        const chatResponse = await chatApi.getById(chatId)
        const routedProjectId = resolveRoutedProjectId(chatResponse.data.chat)
        if (requestId !== routeRequestRef.current) return

        setProjectId(routedProjectId)
        setWorkspace((state) => ({
          ...state,
          prompt:
            [...chatResponse.data.chat.messages]
              .reverse()
              .find((message) => message.role === 'user')?.content ??
            chatResponse.data.chat.title,
        }))

        const snapshots = await refreshProjectData(routedProjectId)
        if (requestId !== routeRequestRef.current) return
        const activeSnapshotId = snapshots?.find((snapshot) => snapshot.isActive)?.id
        if (!activeSnapshotId) return

        const snapshotResponse = await projectApi.getSnapshot(
          routedProjectId,
          activeSnapshotId,
        )
        if (requestId !== routeRequestRef.current) return
        setWorkspace((state) =>
          applyWorkspaceSnapshot(state, snapshotResponse.data.snapshot),
        )
      } catch (error) {
        if (requestId !== routeRequestRef.current) return
        setRouteError(getErrorMessage(error))
      }
    })()
  }, [chatId])

  useEffect(() => () => {
    monitorControllerRef.current?.abort()
  }, [])

  const submitPromptToAgent = async (rawPrompt: string) => {
    const prompt = rawPrompt.trim()

    if (!prompt || workspace.generation.status === 'running' || submissionInFlightRef.current) {
      return
    }

    submissionInFlightRef.current = true
    setSubmissionPending(true)
    const submissionId = ++submissionIdRef.current

    if (!chatId) {
      setDraftPrompt(prompt)
    }
    setWorkspace((state) =>
      startApiGeneration(state, prompt, `pending:${crypto.randomUUID()}`),
    )

    try {
      let activeProjectId = projectId
      let activeChatId = chatId
      let runRequest: Parameters<typeof agentApi.createRun>[0]

      if (!activeChatId) {
        activeProjectId = await createDemoProject(prompt)
        const chatResponse = await chatApi.create(prompt, activeProjectId)
        activeChatId = chatResponse.data.chat._id
        runRequest = {
          projectId: activeProjectId,
          chatId: activeChatId,
          prompt,
          mode: 'create',
        }
      } else {
        runRequest = buildEditRunRequest({
          chatId: activeChatId,
          projectId: activeProjectId,
          prompt,
          activeSnapshotId: workspace.snapshot?.id,
        })
      }

      const runResponse = await agentApi.createRun(runRequest)

      if (submissionId !== submissionIdRef.current) return
      if (!chatId) {
        setProjectId(activeProjectId)
        pendingNavigationChatRef.current = activeChatId
        navigate(buildChatPath(activeChatId))
      }

      monitorControllerRef.current?.abort()
      const controller = new AbortController()
      monitorControllerRef.current = controller
      const token = localStorage.getItem('token')
      if (!token) throw new Error('Authentication token is unavailable')

      const runId = runResponse.data.run._id
      setWorkspace((state) => startApiGeneration(state, prompt, runId))
      const detail = await monitorAgentRun({
        runId,
        token,
        signal: controller.signal,
        onEvent: (event) => {
          setWorkspace((state) => applyAgentEvent(state, runId, event))
        },
      })
      setWorkspace((state) => applyAgentRunDetail(state, detail))
      await refreshProjectData(activeProjectId)
      if (chatId && detail.run.status === 'completed') {
        setEditDraft((current) => current.trim() === prompt ? '' : current)
      }
    } catch (error) {
      if (!isAbortError(error) && submissionId === submissionIdRef.current) {
        setWorkspace((state) => failApiGeneration(state, getErrorMessage(error)))
      }
    } finally {
      if (submissionId === submissionIdRef.current) {
        submissionInFlightRef.current = false
        setSubmissionPending(false)
      }
    }
  }

  const handleCancelRun = async () => {
    const runId = workspace.generation.runId
    if (!isCancellableRunId(runId)) return
    monitorControllerRef.current?.abort()
    monitorControllerRef.current = null
    try {
      const response = await agentApi.cancelRun(runId)
      setWorkspace((state) => applyAgentRunDetail(state, {
        run: response.data.run,
        events: [],
        resultSnapshot: null,
      }))
      if (projectId) await refreshProjectData(projectId)
    } catch (error) {
      setWorkspace((state) => failApiGeneration(state, getErrorMessage(error)))
    }
  }

  const handleBackHome = () => {
    submissionIdRef.current += 1
    submissionInFlightRef.current = false
    setSubmissionPending(false)
    monitorControllerRef.current?.abort()
    monitorControllerRef.current = null
    navigate('/')
  }

  const handleRollback = async (snapshotId: string) => {
    if (!projectId || rollbackInFlightRef.current) return
    rollbackInFlightRef.current = true
    refreshRequestRef.current += 1
    try {
      const response = await projectApi.rollbackSnapshot(projectId, snapshotId)
      setWorkspace((state) => applyWorkspaceSnapshot(state, response.data.snapshot))
      await refreshProjectData(projectId)
    } finally {
      rollbackInFlightRef.current = false
    }
  }

  const handlePromptSubmit = (event?: FormEvent) => {
    event?.preventDefault()
    void submitPromptToAgent(draftPrompt || selectedTemplate.prompt)
  }

  const handleTemplateSelect = (templateId: string) => {
    const next = selectTemplate(workspace, templateId)
    setWorkspace(next)
    setDraftPrompt(next.prompt)
  }

  const handleSuggestion = (label: string) => {
    const prompt = `Build a ${label.toLowerCase()} with polished interactions, responsive states, and production-ready code.`
    setDraftPrompt(prompt)
  }

  const handleCopy = async () => {
    await navigator.clipboard.writeText(currentCode)
    setCopied(true)
    window.setTimeout(() => setCopied(false), 1600)
  }

  const handleDownload = () => {
    const blob = new Blob([currentCode], { type: 'text/plain;charset=utf-8' })
    const url = URL.createObjectURL(blob)
    const anchor = document.createElement('a')
    anchor.href = url
    anchor.download = currentFileName.split('/').pop() ?? 'generated-app.tsx'
    anchor.click()
    URL.revokeObjectURL(url)
  }

  return (
    <div className="min-h-screen bg-[#fafafa] text-neutral-950 antialiased">
      <TopNav />

      {routeError ? (
        <main className="mx-auto flex min-h-[calc(100vh-48px)] max-w-xl items-center px-6 text-center">
          <div className="w-full rounded-lg border border-red-200 bg-red-50 p-5 text-sm text-red-950">
            <p className="font-medium">Unable to load this conversation</p>
            <p className="mt-2" data-testid="chat-route-error">{routeError}</p>
            <button
              className="mt-4 rounded-md bg-neutral-950 px-3 py-2 text-white"
              onClick={handleBackHome}
            >
              Start a new chat
            </button>
          </div>
        </main>
      ) : workspace.screen === 'home' ? (
        <main className="mx-auto w-full max-w-[1240px] px-3 pb-16 pt-20 sm:px-6 lg:pt-32">
          <section className="mx-auto flex max-w-[720px] flex-col items-center text-center">
            <h1 className="text-[28px] font-semibold leading-tight sm:text-[30px]">
              您想创建什么?
            </h1>

            <form
              className="mt-5 w-full rounded-lg border border-neutral-300 bg-white shadow-sm transition focus-within:border-neutral-500 focus-within:shadow-md"
              onSubmit={handlePromptSubmit}
            >
              <textarea
                value={draftPrompt}
                onChange={(event) => setDraftPrompt(event.target.value)}
                onKeyDown={(event) => {
                  if (event.key === 'Enter' && !event.shiftKey) {
                    event.preventDefault()
                    void submitPromptToAgent(draftPrompt || selectedTemplate.prompt)
                  }
                }}
                placeholder="让 v0 构建..."
                className="h-20 w-full resize-none rounded-t-lg bg-transparent px-4 py-4 text-sm leading-6 text-neutral-800 outline-none placeholder:text-neutral-400 sm:h-[74px]"
              />
              <div className="flex items-center justify-between px-3 pb-3">
                <div className="relative">
                  <button
                    type="button"
                    className="inline-flex h-8 items-center gap-2 rounded-md px-2 text-sm text-neutral-600 hover:bg-neutral-100"
                    onClick={() => setModelOpen((open) => !open)}
                  >
                    <Sparkles className="h-4 w-4 text-orange-500" />
                    {model}
                    <ChevronDown className="h-3.5 w-3.5" />
                  </button>
                  {modelOpen ? (
                    <div className="absolute left-0 top-10 z-20 w-44 rounded-lg border border-neutral-200 bg-white p-1 text-left text-sm shadow-xl">
                      {['Mock provider', 'Fable 5', 'Opus 4.5', 'Fast Build'].map((item) => (
                        <button
                          type="button"
                          key={item}
                          className="flex w-full items-center justify-between rounded-md px-3 py-2 text-neutral-700 hover:bg-neutral-100"
                          onClick={() => {
                            setModel(item)
                            setModelOpen(false)
                          }}
                        >
                          {item}
                          {model === item ? <CheckCircle2 className="h-4 w-4" /> : null}
                        </button>
                      ))}
                    </div>
                  ) : null}
                </div>

                <div className="flex items-center gap-2">
                  <button
                    type="button"
                    className="hidden h-8 w-8 items-center justify-center rounded-md text-neutral-500 hover:bg-neutral-100 sm:inline-flex"
                    aria-label="Upload context"
                  >
                    <Upload className="h-4 w-4" />
                  </button>
                  <button
                    type="button"
                    className="h-8 w-8 rounded-md bg-neutral-950 text-white hover:bg-neutral-800"
                    aria-label="Voice prompt"
                  >
                    <Mic className="mx-auto h-4 w-4" />
                  </button>
                  {draftPrompt.trim() ? (
                    <button
                      type="submit"
                      className="inline-flex h-8 w-8 items-center justify-center rounded-md bg-neutral-950 text-white hover:bg-neutral-800 disabled:cursor-not-allowed disabled:bg-neutral-400"
                      aria-label="Build prompt"
                      disabled={workspace.generation.status === 'running'}
                    >
                      {workspace.generation.status === 'running' ? <RefreshCw className="h-4 w-4 animate-spin" /> : <ArrowRight className="h-4 w-4" />}
                    </button>
                  ) : null}
                </div>
              </div>
            </form>

            <div className="mt-4 flex flex-wrap justify-center gap-2">
              {suggestionPrompts.map((label) => {
                const Icon = promptIcons[label]
                return (
                  <button
                    key={label}
                    className="inline-flex h-8 items-center gap-2 rounded-full border border-neutral-200 bg-white px-3 text-sm text-neutral-600 shadow-sm hover:border-neutral-300 hover:bg-neutral-50"
                    onClick={() => handleSuggestion(label)}
                  >
                    <Icon className="h-4 w-4" />
                    {label}
                  </button>
                )
              })}
              <button
                className="inline-flex h-8 w-8 items-center justify-center rounded-full border border-neutral-200 bg-white text-neutral-600 shadow-sm hover:border-neutral-300 hover:bg-neutral-50"
                aria-label="Refresh suggestions"
                onClick={() => setDraftPrompt('Create a clean AI analytics workspace with charts, files, and deploy controls.')}
              >
                <RefreshCw className="h-4 w-4" />
              </button>
            </div>
          </section>

          <section className="mt-24 sm:mt-32">
            <div className="flex flex-col gap-5 sm:flex-row sm:items-center sm:justify-between">
              <h2 className="text-2xl font-semibold">Start with a template</h2>
              <div className="hidden flex-wrap items-center gap-2 sm:flex">
                {categoryFilters.map((filter) => {
                  const Icon = filter.icon
                  const active = category === filter.id
                  return (
                    <button
                      key={filter.id}
                      className={`inline-flex h-8 items-center gap-2 rounded-full border px-3 text-sm ${
                        active
                          ? 'border-neutral-950 bg-neutral-950 text-white'
                          : 'border-neutral-200 bg-white text-neutral-600 hover:bg-neutral-50'
                      }`}
                      onClick={() => setCategory(active ? 'all' : filter.id)}
                    >
                      <Icon className="h-4 w-4" />
                      {filter.label}
                    </button>
                  )
                })}
                <button
                  className="inline-flex h-8 items-center gap-2 rounded-full px-3 text-sm font-medium text-neutral-800 hover:bg-neutral-100"
                  onClick={() => setCategory('all')}
                >
                  Browse all
                  <ArrowRight className="h-4 w-4" />
                </button>
              </div>
            </div>

            <div className="mt-6 grid gap-7 md:grid-cols-2 lg:grid-cols-3">
              {visibleTemplates.map((template) => (
                <TemplateCard
                  key={template.id}
                  template={template}
                  imageSrc={templateImages[template.image]}
                  selected={workspace.selectedTemplateId === template.id}
                  onSelect={() => handleTemplateSelect(template.id)}
                  onBuild={() => {
                    const next = selectTemplate(workspace, template.id)
                    setWorkspace(next)
                    setDraftPrompt(next.prompt)
                    void submitPromptToAgent(next.prompt)
                  }}
                />
              ))}
            </div>
          </section>
        </main>
      ) : (
        <WorkspaceScreen
          prompt={currentPrompt}
          selectedTemplate={selectedTemplate}
          state={workspace}
          designMode={designMode}
          deployOpen={deployOpen}
          copied={copied}
          onBackHome={handleBackHome}
          onSwitchPanel={(panel) => setWorkspace((state) => switchPanel(state, panel))}
          onSelectSnapshotFile={(filePath) =>
            setWorkspace((state) =>
              state.snapshot
                ? {
                    ...state,
                    snapshot: {
                      ...state.snapshot,
                      selectedFilePath: filePath,
                    },
                  }
                : state,
            )
          }
          onToggleDesignMode={() => setDesignMode((enabled) => !enabled)}
          onToggleDeploy={() => setDeployOpen((open) => !open)}
          onCopy={handleCopy}
          onDownload={handleDownload}
          onCancelRun={() => void handleCancelRun()}
          onRollback={(snapshotId) => void handleRollback(snapshotId)}
          currentCode={currentCode}
          currentFileName={currentFileName}
          editDraft={editDraft}
          submissionPending={submissionPending}
          onEditDraftChange={setEditDraft}
          onSubmitEdit={() => void submitPromptToAgent(editDraft)}
          sidebarCollapsed={workspaceSidebarCollapsed}
          onCollapseSidebar={() => setWorkspaceSidebarCollapsed(true)}
          onExpandSidebar={() => setWorkspaceSidebarCollapsed(false)}
        />
      )}
    </div>
  )
}

